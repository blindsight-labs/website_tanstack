/* ---------------- the snapshot every Left renders from ---------------- */
export type Snap = {
  /** section progress, quantised to 0.005 (enough for eased reveals; keeps renders cheap) */
  p: number;
  stage: Stage;
  /** See: FINDS[i] has appeared / has its decision */
  found: boolean[];
  decided: boolean[];
  /** Secure: RUNTIME index being acted on (or -1), and which are done */
  acting: number;
  handled: boolean[];
  /** Govern: LEDGER rows written, the seal, the evidence */
  written: boolean[];
  sealed: boolean;
  evidence: boolean;
  /** the one event happening right now (the only thing allowed the live violet dot), or -1:
   *  See → FINDS index · Secure → RUNTIME index · Govern → LEDGER index */
  current: number;
};

/** the LATEST event whose window is open (windows overlap when rows land 120 ms apart) */
const lastIndex = <T,>(xs: readonly T[], f: (x: T) => boolean) => {
  for (let i = xs.length - 1; i >= 0; i--) if (f(xs[i])) return i;
  return -1;
};
function currentAt(p: number) {
  const st = stageOf(p);
  if (st === 0) return lastIndex(FINDS, (f) => p >= f.at && p < f.at + DECIDE);
  if (st === 1) return lastIndex(RUNTIME, (e) => p >= e.t0 && p < e.t1 + HOLD_DOT);
  // Govern: the dot rides the row being written, until the next one lands; it goes out at the seal
  if (p >= SEALED.p) return -1;
  return lastIndex(LEDGER_AT, (t) => p >= t);
}

export function snapAt(p: number): Snap {
  return {
    p: Math.round(p * 200) / 200,
    stage: stageOf(p),
    found: FINDS.map((f) => p >= f.at),
    decided: FINDS.map((f) => p >= f.at + DECIDE),
    acting: RUNTIME.findIndex((e) => p >= e.t0 && p < e.t1),
    handled: RUNTIME.map((e) => p >= e.t1),
    written: LEDGER_AT.map((t) => p >= t),
    sealed: p >= SEALED.p,
    evidence: p >= EVIDENCE_P,
    current: currentAt(p),
  };
}
