/* ---------------- the two clocks ---------------- */
export const STAGE_P = [0.34, 0.67] as const;
export const BOUNDS = [0, STAGE_P[0], STAGE_P[1], 1];
export const pOf = (ms: number) =>
  ms < 5000
    ? (ms / 5000) * STAGE_P[0]
    : ms < 11000
      ? STAGE_P[0] + ((ms - 5000) / 6000) * (STAGE_P[1] - STAGE_P[0])
      : STAGE_P[1] + ((ms - 11000) / 3600) * (1 - STAGE_P[1]);
export const netTime = (p: number) =>
  p < BOUNDS[1]
    ? (p / BOUNDS[1]) * 5000
    : p < BOUNDS[2]
      ? 5000 + ((p - BOUNDS[1]) / (BOUNDS[2] - BOUNDS[1])) * 6000
      : 11000 + ((p - BOUNDS[2]) / (1 - BOUNDS[2])) * 3600;

/** Settled end state of each stage (stills, reduced motion, a click on a step). */
export const SETTLED = [0.33, 0.66, 1];
/** Playback: ms per stage (the close-up's beats), and the hold before it loops. */
/** PACE stretches the playback so every caption can be read as it lands (owner: "too fast").
 *  The close-up still draws storyboard time t = netTime(p); only the clock runs slower. */
export const PACE = 1.8;
export const STAGE_MS = [5000, 6000, 3600].map((ms) => ms * PACE);
export const HOLD_MS = 5200;

export const clamp01 = (x: number) => (x < 0 ? 0 : x > 1 ? 1 : x);
export const seg = (p: number, a: number, b: number) => clamp01((p - a) / (b - a));
export const stageOf = (p: number): Stage => (p < STAGE_P[0] ? 0 : p < STAGE_P[1] ? 1 : 2);
export const stageLocal = (p: number, k: number) => seg(p, BOUNDS[k], BOUNDS[k + 1]);

